"""Vulnerability Assessment Template Definitions.

Comprehensive 30 multi-tool templates designed to extract the maximum number of
actionable vulnerabilities and misconfigurations across specific target perimeters.
Each template chains 5 to 9 distinct security tools with fine-tuned parameters
and execution stages.
"""

from typing import Any, Optional
from pydantic import BaseModel, Field

try:
    from schemas import ScannerName
except (ImportError, AttributeError):
    try:
        from ..schemas import ScannerName
    except Exception:
        import importlib
        backend_schemas = importlib.import_module("src.backend.schemas")
        ScannerName = backend_schemas.ScannerName


class ToolChainStep(BaseModel):
    tool: ScannerName
    order: int
    purpose: str
    flags: list[str] = Field(default_factory=list)
    nuclei_tags: list[str] = Field(default_factory=list)


class ScanTemplate(BaseModel):
    id: str
    name: str
    category: str
    badge: str
    description: str
    profile: str = "web"
    scanners: list[ScannerName]
    tool_chain: list[ToolChainStep]
    nuclei_tags: list[str] = Field(default_factory=list)
    target_type: str = "any"  # "web_url", "domain_or_ip", "api_endpoint", "any"
    estimated_duration_sec: int = 45
    vulnerability_focus: list[str] = Field(default_factory=list)
    is_default: bool = False

    @property
    def tools(self) -> list[str]:
        return [s.value if hasattr(s, "value") else str(s) for s in self.scanners]


